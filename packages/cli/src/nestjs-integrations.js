import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Separate registries keep module imports out of entity and audit initialization.
// Importing feature modules from the audit service would create circular imports.
export function writeNestjsIntegrations(destination, backend, extensions) {
  const selected = extensions.filter((extension) => extension.integrations?.nestjs);
  if (backend?.id !== 'backend:nestjs') {
    if (selected.length) throw new Error('NestJS integrations require backend:nestjs.');
    return;
  }
  const output = join(destination, 'backend', 'src', 'extensions');
  mkdirSync(output, { recursive: true });
  const lists = { modules: [], entities: [], migrations: [] };
  const actions = new Map();
  for (const extension of selected) {
    const integration = extension.integrations.nestjs;
    const target = extension.targets.find(({ template }) => template === 'backend:nestjs');
    if (!target) throw new Error('NestJS integrations require a backend:nestjs target.');
    for (const kind of Object.keys(lists)) {
      for (const reference of integration[kind] ?? []) {
        if (lists[kind].includes(reference)) throw new Error(`Duplicate NestJS ${kind} reference: ${reference}`);
        const [path] = reference.split(':');
        if (['src/extensions/modules.generated', 'src/extensions/database.generated', 'src/extensions/audit.generated'].includes(path)
          || !existsSync(join(destination, 'backend', path + '.ts'))) {
          throw new Error(`NestJS integration source does not exist or is reserved: ${reference}`);
        }
        if (kind === 'migrations' && !target.migrations.includes(path + '.ts')) {
          throw new Error(`NestJS migration must be declared in its target: ${reference}`);
        }
        lists[kind].push(reference);
      }
    }
    for (const action of integration.auditActions ?? []) {
      if (actions.has(action.name)) throw new Error(`Duplicate NestJS audit action: ${action.name}`);
      const { name, ...definition } = action;
      actions.set(name, definition);
    }
  }
  const header = '// Generated by create-my-saas from integrations.nestjs. Do not edit manually.\n';
  function imports(references, prefix) {
    return references.map((reference, index) => {
      const [path, symbol] = reference.split(':');
      return `import { ${symbol} as ${prefix}${index} } from '../${path.slice(4)}';`;
    }).join('\n');
  }
  const aliases = (references, prefix) => references.map((_, index) => prefix + index).join(', ');
  writeFileSync(join(output, 'modules.generated.ts'), header + "import type { Type } from '@nestjs/common';\n"
    + imports(lists.modules, 'ExtensionModule') + '\n\n'
    + `export const extensionModules: Type<unknown>[] = [${aliases(lists.modules, 'ExtensionModule')}];\n`);
  writeFileSync(join(output, 'database.generated.ts'), header + "import type { DataSourceOptions } from 'typeorm';\n"
    + imports(lists.entities, 'ExtensionEntity') + '\n' + imports(lists.migrations, 'ExtensionMigration') + '\n\n'
    + `export const extensionEntities: Extract<NonNullable<DataSourceOptions['entities']>, unknown[]> = [${aliases(lists.entities, 'ExtensionEntity')}];\n`
    + `export const extensionMigrations: Extract<NonNullable<DataSourceOptions['migrations']>, unknown[]> = [${aliases(lists.migrations, 'ExtensionMigration')}];\n`);
  writeFileSync(join(output, 'audit.generated.ts'), header + "import type { AuditActionDefinition } from './audit-registry';\n\n"
    + `export const extensionAuditActions: Record<string, AuditActionDefinition> = ${JSON.stringify(Object.fromEntries(actions), null, 2)};\n`);
}
