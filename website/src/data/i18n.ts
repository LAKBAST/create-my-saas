// La web se publica en español en la raíz y en inglés bajo /en/.
export const langs = ['es', 'en'] as const;
export type Lang = (typeof langs)[number];

export const htmlLang: Record<Lang, string> = { es: 'es', en: 'en' };
export const ogLocale: Record<Lang, string> = { es: 'es_ES', en: 'en_US' };

/** Idioma de una ruta: inglés si empieza por {BASE_URL}en/. */
export const langFromPath = (pathname: string): Lang =>
	pathname.startsWith(`${import.meta.env.BASE_URL.replace(/\/$/, '')}/en/`) ? 'en' : 'es';

/** Ruta relativa a la raíz de la web con el prefijo del idioma: lp('en', 'pro/') → 'en/pro/'. */
export const lp = (lang: Lang, path = '') => (lang === 'es' ? path : `en/${path}`);

